# Importación de librerías necesarias
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import MinMaxScaler, LabelEncoder, OneHotEncoder
from sklearn.svm import SVR
from sklearn.metrics import r2_score
from sklearn.impute import SimpleImputer
import seaborn as sns

# 1. Cargar el dataset
print("1. CARGANDO EL DATASET")
# Utilizaremos el Auto MPG Dataset de UCI Repository
url = "https://archive.ics.uci.edu/ml/machine-learning-databases/auto-mpg/auto-mpg.data"
# Nombres de columnas en español más fáciles de entender
nombres_columnas = ['consumo', 'cilindros', 'cilindrada', 'potencia', 'peso',
                    'aceleracion', 'año_modelo', 'origen', 'nombre_auto']
datos = pd.read_csv(url, delim_whitespace=True, names=nombres_columnas)

# Mostrar las primeras filas del dataset para entenderlo
print("\nPrimeras filas del dataset:")
print(datos.head())

# Información general del dataset
print("\nInformación del dataset:")
print(datos.info())

# Estadísticas descriptivas
print("\nEstadísticas descriptivas:")
print(datos.describe())

# Verificar si hay valores faltantes
print("\nValores faltantes por columna:")
print(datos.isnull().sum())

# Verificar valores únicos en columnas categóricas
print("\nValores únicos en columnas categóricas:")
print("Origen:", datos['origen'].unique())
print("Año del modelo:", datos['año_modelo'].unique())

# 2. Preprocesamiento de los datos
print("\n2. PREPROCESAMIENTO DE LOS DATOS")

# 2.1 Eliminar la columna 'nombre_auto' que no es relevante para la predicción
datos = datos.drop('nombre_auto', axis=1)
print("\nColumnas después de eliminar 'nombre_auto':", datos.columns.tolist())

# 2.2 Identificar y reemplazar valores '?' que indican valores faltantes
print("\nVerificar si hay valores '?' en el dataset:")
for columna in datos.columns:
    valores_faltantes = (datos[columna] == '?').sum()
    if valores_faltantes > 0:
        print(f"La columna {columna} tiene {valores_faltantes} valores '?'")
# Reemplazar '?' con NaN para facilitar el manejo de datos faltantes
datos = datos.replace('?', np.nan)

# Convertir columnas a tipos numéricos (algunas podrían ser strings por los valores '?')
for columna in datos.columns:
    if columna != 'origen':  # Solo convertimos las columnas numéricas
        datos[columna] = pd.to_numeric(datos[columna], errors='coerce')

print("\nValores faltantes después de la conversión:")
print(datos.isnull().sum())

# 2.3 Imputar valores faltantes para columnas numéricas
columnas_con_nulos = datos.columns[datos.isnull().any()].tolist()
if columnas_con_nulos:
    print(f"\nImputando valores faltantes en columnas: {columnas_con_nulos}")
    for columna in columnas_con_nulos:
        if columna != 'origen':  # Solo imputamos columnas numéricas
            imputador = SimpleImputer(strategy='mean')
            datos[[columna]] = imputador.fit_transform(datos[[columna]])

print("\nValores faltantes después de la imputación:")
print(datos.isnull().sum())

# 2.4 Convertir variables categóricas a numéricas
# La columna 'origen' es categórica (1 = USA, 2 = Europa, 3 = Asia)
print("\nConvirtiendo variable categórica 'origen' con OneHotEncoder:")
try:
    # Para versiones más recientes de scikit-learn (>=1.2)
    codificador = OneHotEncoder(sparse_output=False, drop='first')
    origen_codificado = codificador.fit_transform(datos[['origen']])
except TypeError:
    # Para versiones anteriores de scikit-learn
    codificador = OneHotEncoder(sparse=False, drop='first')
    origen_codificado = codificador.fit_transform(datos[['origen']])

# Creamos un DataFrame con las variables codificadas
origen_df = pd.DataFrame(origen_codificado, columns=['origen_europa', 'origen_asia'])
# Combinamos el DataFrame original (sin 'origen') con las nuevas columnas
