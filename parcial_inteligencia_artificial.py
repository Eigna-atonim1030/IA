print("\nColumnas después de la codificación one-hot:")
print(datos.columns.tolist())

# 2.5 Normalización de variables numéricas entre 0 y 1
print("\nNormalizando variables numéricas con MinMaxScaler:")
# Seleccionamos la variable objetivo y las características
y_objetivo = datos['consumo']  # Variable objetivo: consumo de combustible en millas por galón
X_caracteristicas = datos.drop('consumo', axis=1)

# Aplicamos MinMaxScaler para normalizar las características
normalizador = MinMaxScaler()
X_normalizado = normalizador.fit_transform(X_caracteristicas)
X_normalizado_df = pd.DataFrame(X_normalizado, columns=X_caracteristicas.columns)

# Mostrar los datos después del preprocesamiento
print("\nDatos después del preprocesamiento (primeras 5 filas):")
print(X_normalizado_df.head())

# 3. División de datos en conjuntos de entrenamiento y prueba
print("\n3. DIVISIÓN DE DATOS EN CONJUNTOS DE ENTRENAMIENTO Y PRUEBA")
X_entrenamiento, X_prueba, y_entrenamiento, y_prueba = train_test_split(
    X_normalizado, y_objetivo, test_size=0.2, random_state=42)

print(f"X_entrenamiento: {X_entrenamiento.shape}")
print(f"X_prueba: {X_prueba.shape}")
print(f"y_entrenamiento: {y_entrenamiento.shape}")
print(f"y_prueba: {y_prueba.shape}")

# 4. Modelado con SVR y optimización de hiperparámetros con GridSearchCV
print("\n4. MODELADO CON SVR Y OPTIMIZACIÓN DE HIPERPARÁMETROS")
# Definir los hiperparámetros a probar
parametros_a_probar = {
    'kernel': ['linear', 'poly', 'rbf', 'sigmoid'],
    'C': [0.1, 1, 10, 100],
    'epsilon': [0.01, 0.1, 0.2, 0.5]
}

# Crear el modelo SVR
modelo_svr = SVR()

# Crear el objeto GridSearchCV
buscador_parametros = GridSearchCV(modelo_svr, parametros_a_probar, cv=5,
                                  scoring='r2', n_jobs=-1, verbose=1)

# Entrenar el modelo con GridSearchCV
print("\nEntrenando modelo con GridSearchCV (esto puede tardar unos minutos)...")
buscador_parametros.fit(X_entrenamiento, y_entrenamiento)

# Mostrar los mejores hiperparámetros encontrados
print("\nMejores hiperparámetros encontrados:")
print(buscador_parametros.best_params_)

# Obtener el mejor modelo
mejor_modelo = buscador_parametros.best_estimator_

# 5. Evaluación del modelo
print("\n5. EVALUACIÓN DEL MODELO")
# Realizar predicciones en el conjunto de prueba
y_predicciones = mejor_modelo.predict(X_prueba)

# Calcular el coeficiente de determinación R²
r2 = r2_score(y_prueba, y_predicciones)
print(f"\nR² score en el conjunto de prueba: {r2:.4f}")

# Crear índices para el gráfico
indices = range(len(y_prueba))

# Visualización 1: Scatter plot de valores reales vs predichos (CORREGIDO)
plt.figure(figsize=(12, 8))
plt.scatter(indices, y_prueba, color='orange', alpha=0.8, s=70, label='Valores reales (y_prueba)')
plt.scatter(indices, y_predicciones, color='blue', alpha=0.6, s=40, label='Valores predichos (y_predicciones)')

# Establecer explícitamente los límites de los ejes
min_y = min(min(y_prueba), min(y_predicciones)) * 0.95
max_y = max(max(y_prueba), max(y_predicciones)) * 1.05
plt.ylim(min_y, max_y)
plt.xlim(-1, len(indices))

# Configuración del gráfico
plt.title(f'Comparación de valores reales vs predichos (R² = {r2:.4f})', fontsize=14)
plt.xlabel('Índice de muestra', fontsize=12)
plt.ylabel('Consumo (millas por galón)', fontsize=12)
plt.legend(fontsize=12)
plt.grid(True, linestyle='--', alpha=0.6)
plt.tight_layout()

# Guardamos la figura con alta resolución
plt.savefig('comparacion_real_vs_predicho.png', dpi=300)
plt.show()

# Visualización 2: Análisis de residuos
plt.figure(figsize=(10, 6))
errores = y_prueba - y_predicciones
