plt.axhline(y=0, color='r', linestyle='-')
plt.xlabel('Valores predichos', fontsize=12)
plt.ylabel('Errores', fontsize=12)
plt.title('Análisis de errores', fontsize=14)
plt.grid(True)
plt.savefig('analisis_errores.png', dpi=300)
plt.show()

# Visualización 3: Histograma de residuos
plt.figure(figsize=(10, 6))
plt.hist(errores, bins=20, color='purple', alpha=0.7)
plt.axvline(x=0, color='r', linestyle='-')
plt.xlabel('Errores', fontsize=12)
plt.ylabel('Frecuencia', fontsize=12)
plt.title('Distribución de errores', fontsize=14)
plt.grid(True)
plt.savefig('distribucion_errores.png', dpi=300)
plt.show()

# 6. Resumen final
print("\n=== RESUMEN FINAL ===")
print(f"Mejor modelo: SVR con kernel {mejor_modelo.kernel}")
print(f"Valor de C: {mejor_modelo.C}")
print(f"Valor de epsilon: {mejor_modelo.epsilon}")
print(f"Puntuación R²: {r2:.4f}")
print("=====================")